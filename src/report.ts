const SCRIPT = `
(function(){
  // Generic sortable tables.
  document.querySelectorAll("table.sortable").forEach(function(table){
    var headers = table.querySelectorAll("th[data-key]");
    headers.forEach(function(th, idx){
      th.addEventListener("click", function(){
        var numeric = th.getAttribute("data-type") === "num";
        var current = th.getAttribute("aria-sort");
        var asc = current !== "ascending";
        headers.forEach(function(h){ h.removeAttribute("aria-sort"); });
        th.setAttribute("aria-sort", asc ? "ascending" : "descending");
        var tbody = table.tBodies[0];
        var rows = Array.prototype.slice.call(tbody.rows);
        rows.sort(function(a,b){
          var av = cell(a, idx, numeric), bv = cell(b, idx, numeric);
          if (av < bv) return asc ? -1 : 1;
          if (av > bv) return asc ? 1 : -1;
          return 0;
        });
        rows.forEach(function(r){ tbody.appendChild(r); });
      });
    });
    function cell(row, idx, numeric){
      var td = row.cells[idx];
      var v = td.getAttribute("data-sort");
      if (v === null) v = td.textContent.trim();
      return numeric ? parseFloat(v) || 0 : v.toLowerCase();
    }
  });

  // Hot-spot filter box.
  var filter = document.getElementById("filter");
  if (filter){
    var table = document.getElementById("hotspots");
    filter.addEventListener("input", function(){
      var q = filter.value.toLowerCase();
      Array.prototype.forEach.call(table.tBodies[0].rows, function(row){
        row.style.display = row.textContent.toLowerCase().indexOf(q) === -1 ? "none" : "";
      });
    });
  }
})();
`;
