import { SEVERITY_THRESHOLDS } from "./analyze.js";
import type { FileReport, ProjectReport, Severity } from "./types.js";

const SEVERITY_LABEL: Record<Severity, string> = {
  low: "Low",
  moderate: "Moderate",
  high: "High",
  veryHigh: "Very high",
};

/** Render a {@link ProjectReport} as a single self-contained HTML document. */
export function renderHtml(report: ProjectReport): string {
  const { summary } = report;
  const generated = new Date(report.generatedAt).toLocaleString();
  const filesWithFns = report.files.filter((f) => f.functions.length > 0);

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Complexity Radar — ${escapeHtml(report.root)}</title>
<style>${STYLE}</style>
</head>
<body>
<header class="topbar">
  <div class="brand"><span class="logo">◎</span> Complexity Radar</div>
  <div class="meta">
    <span title="${escapeHtml(report.root)}">${escapeHtml(shortenPath(report.root))}</span>
    <span class="dot">•</span>
    <span>${escapeHtml(generated)}</span>
  </div>
</header>

<main>
  <section class="cards">
    ${card("Files", fmt(summary.fileCount))}
    ${card("Functions", fmt(summary.functionCount))}
    ${card("Lines of code", fmt(summary.totalLoc))}
    ${card("Avg complexity", summary.avgComplexity.toFixed(1))}
    ${card("Max complexity", fmt(summary.maxComplexity), severityFor(summary.maxComplexity))}
    ${thresholdCard(summary.threshold, summary.overThreshold)}
  </section>

  <section class="panel">
    <h2>Severity distribution</h2>
    ${severityBar(summary.severity, summary.functionCount)}
    <p class="legend">
      ${legendItem("low", `≤ ${SEVERITY_THRESHOLDS.moderate - 1}`)}
      ${legendItem("moderate", `${SEVERITY_THRESHOLDS.moderate}–${SEVERITY_THRESHOLDS.high - 1}`)}
      ${legendItem("high", `${SEVERITY_THRESHOLDS.high}–${SEVERITY_THRESHOLDS.veryHigh - 1}`)}
      ${legendItem("veryHigh", `≥ ${SEVERITY_THRESHOLDS.veryHigh}`)}
    </p>
  </section>

  <section class="panel">
    <h2>Hot spots <span class="subtle">worst ${summary.hotspots.length} functions</span></h2>
    <input id="filter" class="filter" type="search" placeholder="Filter by function or file…" aria-label="Filter hot spots">
    ${hotspotTable(report)}
  </section>

  <section class="panel">
    <h2>By language</h2>
    ${languageTable(report)}
  </section>

  <section class="panel">
    <h2>Files <span class="subtle">${filesWithFns.length} with functions</span></h2>
    <div class="files">
      ${filesWithFns.map(fileBlock).join("\n")}
      ${filesWithFns.length === 0 ? '<p class="subtle">No functions were detected.</p>' : ""}
    </div>
  </section>

  <footer class="foot">
    <p>Generated by <strong>Complexity Radar</strong>. Cyclomatic complexity is
    computed heuristically (1 + decision points) without a full parser, so treat
    scores as directional rather than exact — especially for Java and C#.</p>
  </footer>
</main>

<script>${SCRIPT}</script>
</body>
</html>`;
}

function card(label: string, value: string, sev?: Severity): string {
  const cls = sev ? ` sev-${sev}` : "";
  return `<div class="card${cls}"><div class="card-value">${value}</div><div class="card-label">${label}</div></div>`;
}

function thresholdCard(threshold: number | null, over: number): string {
  if (threshold === null) return card("Over threshold", "—");
  const sev: Severity = over > 0 ? "high" : "low";
  return card(`Over threshold (${threshold})`, fmt(over), sev);
}

function severityBar(sev: Record<Severity, number>, total: number): string {
  if (total === 0) return '<div class="bar empty"></div>';
  const seg = (s: Severity) => {
    const pct = (sev[s] / total) * 100;
    if (pct === 0) return "";
    return `<div class="seg seg-${s}" style="width:${pct.toFixed(2)}%" title="${SEVERITY_LABEL[s]}: ${sev[s]}"></div>`;
  };
  return `<div class="bar">${seg("low")}${seg("moderate")}${seg("high")}${seg("veryHigh")}</div>`;
}

function legendItem(sev: Severity, range: string): string {
  return `<span class="leg"><span class="swatch sw-${sev}"></span>${SEVERITY_LABEL[sev]} <span class="subtle">(${range})</span></span>`;
}

function hotspotTable(report: ProjectReport): string {
  if (report.summary.hotspots.length === 0) {
    return '<p class="subtle">Nothing to show.</p>';
  }
  const rows = report.summary.hotspots
    .map(
      (h) => `<tr>
      <td data-sort="${escapeAttr(h.name)}"><code>${escapeHtml(h.name)}</code></td>
      <td data-sort="${escapeAttr(h.relPath)}" class="path"><span title="${escapeHtml(h.relPath)}">${escapeHtml(h.relPath)}</span><span class="subtle">:${h.line}</span></td>
      <td data-sort="${escapeAttr(h.language)}">${escapeHtml(h.language)}</td>
      <td data-type="num" data-sort="${h.complexity}">${badge(h.complexity, h.severity)}</td>
      <td data-type="num" data-sort="${h.loc}">${h.loc}</td>
      <td data-type="num" data-sort="${h.maxNesting}">${h.maxNesting}</td>
      <td data-type="num" data-sort="${h.params}">${h.params}</td>
    </tr>`,
    )
    .join("\n");
  return `<div class="table-wrap"><table class="sortable" id="hotspots">
    <thead><tr>
      <th data-key>Function</th>
      <th data-key>File</th>
      <th data-key>Lang</th>
      <th data-key data-type="num" class="num" aria-sort="descending">Complexity</th>
      <th data-key data-type="num" class="num">LOC</th>
      <th data-key data-type="num" class="num">Nesting</th>
      <th data-key data-type="num" class="num">Params</th>
    </tr></thead>
    <tbody>${rows}</tbody>
  </table></div>`;
}

function languageTable(report: ProjectReport): string {
  const rows = report.summary.byLanguage
    .map(
      (l) => `<tr>
      <td>${escapeHtml(l.language)}</td>
      <td data-type="num">${l.files}</td>
      <td data-type="num">${l.functions}</td>
      <td data-type="num">${fmt(l.totalLoc)}</td>
      <td data-type="num">${l.avgComplexity.toFixed(1)}</td>
      <td data-type="num">${badge(l.maxComplexity, severityFor(l.maxComplexity))}</td>
    </tr>`,
    )
    .join("\n");
  return `<div class="table-wrap"><table>
    <thead><tr>
      <th>Language</th><th class="num">Files</th><th class="num">Functions</th>
      <th class="num">LOC</th><th class="num">Avg</th><th class="num">Max</th>
    </tr></thead>
    <tbody>${rows}</tbody>
  </table></div>`;
}

function fileBlock(file: FileReport): string {
  const worst = file.maxComplexity;
  const rows = file.functions
    .slice()
    .sort((a, b) => b.complexity - a.complexity)
    .map(
      (fn) => `<tr>
        <td><code>${escapeHtml(fn.name)}</code> <span class="subtle">:${fn.line}</span></td>
        <td data-type="num">${badge(fn.complexity, fn.severity)}</td>
        <td data-type="num">${fn.loc}</td>
        <td data-type="num">${fn.maxNesting}</td>
        <td data-type="num">${fn.params}</td>
      </tr>`,
    )
    .join("\n");
  return `<details class="file">
    <summary>
      <span class="fname">${escapeHtml(file.relPath)}</span>
      <span class="fmeta">
        <span class="subtle">${file.functions.length} fn · ${file.loc} LOC</span>
        ${badge(worst, severityFor(worst))}
      </span>
    </summary>
    <div class="table-wrap"><table>
      <thead><tr><th>Function</th><th class="num">Complexity</th><th class="num">LOC</th><th class="num">Nesting</th><th class="num">Params</th></tr></thead>
      <tbody>${rows}</tbody>
    </table></div>
  </details>`;
}

function badge(value: number, sev: Severity): string {
  return `<span class="badge b-${sev}">${value}</span>`;
}

function severityFor(complexity: number): Severity {
  if (complexity >= SEVERITY_THRESHOLDS.veryHigh) return "veryHigh";
  if (complexity >= SEVERITY_THRESHOLDS.high) return "high";
  if (complexity >= SEVERITY_THRESHOLDS.moderate) return "moderate";
  return "low";
}

function fmt(n: number): string {
  return n.toLocaleString("en-US");
}

function shortenPath(p: string, max = 60): string {
  return p.length <= max ? p : "…" + p.slice(p.length - max + 1);
}

function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) =>
    c === "&" ? "&amp;" : c === "<" ? "&lt;" : c === ">" ? "&gt;" : c === '"' ? "&quot;" : "&#39;",
  );
}

function escapeAttr(s: string): string {
  return escapeHtml(s);
}

